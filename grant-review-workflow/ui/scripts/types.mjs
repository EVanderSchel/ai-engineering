// Generates src/api/types.ts from src/api/schema.json, which the Python API exports (api.contract()).
// src/api/types.test.ts fails when the two disagree.
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { compile } from 'json-schema-to-typescript';

export const BANNER = "// Generated by `npm run types` from schema.json (the Python API's models). Do not edit.";

export async function generate() {
  const schema = JSON.parse(await readFile(new URL('../src/api/schema.json', import.meta.url), 'utf8'));
  return compile(schema, 'ReviewerApi', { bannerComment: BANNER, additionalProperties: false, format: true });
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL('../src/api/types.ts', import.meta.url), await generate());
  console.log('wrote src/api/types.ts');
}
